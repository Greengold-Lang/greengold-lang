"""Writes docs/API.md, the standard library reference, from the library's own source (the same catalog as `gg api`).

    python tools/build_api_docs.py           # rewrite docs/API.md
    python tools/build_api_docs.py --check   # exit 1 when docs/API.md is out of date
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from greengold.api import library  # noqa: E402

OUT = ROOT / "docs" / "API.md"
TITLES = {"builtin": "Compiler builtins", "core": "Core prelude (always in scope)"}
KINDS = ["struct", "enum", "feature", "const", "fn", "extern", "builtin"]


def render() -> str:
    doc = library()
    modules: dict[str, list[dict]] = {}
    for sym in doc["symbols"]:
        modules.setdefault(sym["module"], []).append(sym)
    out = [
        "# Greengold API reference",
        "",
        "Generated by `python tools/build_api_docs.py` from `greengold/core/core.gg`, `greengold/std/*.gg` and the compiler "
        "builtins. Do not edit by hand; `gg api` and `gg api --json` print the same catalog. Prose and examples: "
        "[SPEC.md](SPEC.md) (modules) and [Learn/09](../Learn/09_Standard_Library_and_Concurrency.md).",
        "",
        "Import a module with `import std.math`, then call `math.sqrt(4.0)`, or bring names in with "
        "`import std.math { sqrt }`. The core prelude and builtins need no import.",
        "",
        "## Modules",
        "",
    ]
    for name in modules:
        out.append(f"- [{TITLES.get(name, name)}](#{_anchor(TITLES.get(name, name))}) ({len(modules[name])})")
    out.append("- [Not in the catalog](#not-in-the-catalog): attributes, intrinsics, JSON output formats")
    for name, syms in modules.items():
        out += ["", f"## {TITLES.get(name, name)}", ""]
        for kind in KINDS:
            group = [s for s in syms if s["kind"] == kind]
            if not group:
                continue
            out += [f"### {kind}", ""]
            for s in group:
                out.append("```")
                out.append(s["signature"])
                out.append("```")
                if s["description"]:
                    out.append(s["description"])
                out.append("")
    extra = (ROOT / "docs" / "api_extra.md").read_text(encoding="utf-8").strip()
    return "\n".join(out).rstrip() + "\n\n" + extra + "\n"


def _anchor(title: str) -> str:
    return "".join(c for c in title.lower().replace(" ", "-") if c.isalnum() or c == "-")


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/API.md is out of date: run python tools/build_api_docs.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
