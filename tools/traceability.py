"""Requirements traceability: which part of docs/SPEC.md is pinned down by which test.

    python tools/traceability.py            # writes docs/TRACEABILITY.md
    python tools/traceability.py --check    # exit 1 when the file is stale, or a SPEC section has no conformance program and no unit-test module

Two sources are joined per SPEC section (`## N. Title`):

* conformance programs in `conformance/`: the header `# conformance: SPEC section N ...` says which section a program pins down, and
  the header also states whether it must print something (an accepted example) or fail with a code (a rejected form);
* unit-test modules that declare `Spec: N, M` on a line of their docstring.

A section with neither is a gap in the evidence, and `--check` fails on it, so a new rule cannot be added to the
spec without a program that shows it. This is traceability at section level, the granularity the spec is written in; it is
not a substitute for the tracing a certification authority asks for at the level of individual requirements.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs" / "SPEC.md"
OUT = ROOT / "docs" / "TRACEABILITY.md"
HEADING = re.compile(r"^## (\d+)\. (.+)$", re.M)
CONFORMANCE = re.compile(r"^# conformance: SPEC section (\d+)\b(.*)$", re.M)
UNIT = re.compile(r"^Spec:\s*([\d,\s]+)$", re.M)


def sections() -> dict[int, str]:
    return {int(n): title.strip() for n, title in HEADING.findall(SPEC.read_text(encoding="utf-8"))}


def conformance() -> dict[int, list[tuple[str, str]]]:
    found: dict[int, list[tuple[str, str]]] = {}
    for path in sorted((ROOT / "conformance").rglob("*.gg")):
        head = "\n".join(path.read_text(encoding="utf-8").splitlines()[:6])
        m = CONFORMANCE.search(head)
        if not m:
            continue
        kind = "rejected form" if "expect-error" in head else "example"
        found.setdefault(int(m.group(1)), []).append((path.relative_to(ROOT).as_posix(), kind))
    return found


def unit_tests() -> dict[int, list[str]]:
    found: dict[int, list[str]] = {}
    for path in sorted((ROOT / "tests").glob("test_*.py")):
        text = path.read_text(encoding="utf-8")
        doc = re.match(r'\s*"""(.*?)"""', text, re.S)
        if not doc:
            continue
        for m in UNIT.finditer(doc.group(1)):
            for n in re.findall(r"\d+", m.group(1)):
                found.setdefault(int(n), []).append(path.relative_to(ROOT).as_posix())
    return found


def render() -> str:
    secs, conf, units = sections(), conformance(), unit_tests()
    lines = [
        "# Requirements traceability",
        "",
        "Generated by `python tools/traceability.py` from `docs/SPEC.md`, the headers of `conformance/**/*.gg`, and the `Spec:` lines in",
        "the docstrings of `tests/test_*.py`. Do not edit by hand. Section level only: the spec's sections are the requirements here.",
        "",
        "| SPEC section | Examples | Rejected forms | Unit-test modules |",
        "|---|---|---|---|",
    ]
    gaps = []
    for n, title in secs.items():
        cases = conf.get(n, [])
        ex = sum(1 for _, k in cases if k == "example")
        rej = sum(1 for _, k in cases if k == "rejected form")
        mods = sorted(set(units.get(n, [])))
        if not cases and not mods:
            gaps.append(n)
        lines.append(f"| {n}. {title} | {ex} | {rej} | {', '.join(f'`{m}`' for m in mods) or '-'} |")
    lines += ["", f"{sum(len(v) for v in conf.values())} conformance programs cover {len(conf)} of {len(secs)} sections."]
    if gaps:
        lines += ["", "**Sections with neither a conformance program nor a unit-test module:** " + ", ".join(str(n) for n in gaps) + "."]
    lines += ["", "## Programs by section", ""]
    for n, title in secs.items():
        lines.append(f"### {n}. {title}")
        lines.append("")
        for path, kind in conf.get(n, []):
            lines.append(f"- `{path}` ({kind})")
        if not conf.get(n):
            lines.append("- none")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        stale = not OUT.exists() or OUT.read_text(encoding="utf-8") != text
        gaps = "Sections with neither" in text
        if stale:
            print("docs/TRACEABILITY.md is stale: run python tools/traceability.py", file=sys.stderr)
        if gaps:
            print([ln for ln in text.splitlines() if ln.startswith("**Sections with neither")][0], file=sys.stderr)
        return 1 if stale or gaps else 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
